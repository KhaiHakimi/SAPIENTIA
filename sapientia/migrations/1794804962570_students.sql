-- Up Migration
-- Phase 4, Sprint 11: pupil accounts, their class, and their sessions. Sprint 12: homework and paper hand-ins. Sprint 13:
-- guardians, their links to pupils, their sessions, and their meeting requests. Sprint 14: removed staff logins and
-- homework comments. See docs/phase-4-students.md.
-- Data minimisation: a pupil is a name, a class and an optional school-issued number. No MyKad number, birth date,
-- address, contact details, photo or sign-in times are stored.

CREATE TYPE student_status AS ENUM ('active', 'disabled');

-- Pupils are not rows in users: no staff query can return a pupil, and no pupil session can pass a staff check.
CREATE TABLE students (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools (id),
  name text NOT NULL,
  school_number text,
  -- Generated by the app (first-name letters plus digits), stored in lower case, unique across schools: sign-in has only it.
  username text NOT NULL,
  -- argon2id in PHC form: of the starting password from the slip until the pupil chooses their own.
  password_hash text NOT NULL,
  must_change_password boolean NOT NULL DEFAULT true,
  -- The slip's password stops working at this time; null once the pupil has chosen their own.
  starting_password_expires_at timestamptz,
  status student_status NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT students_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT students_school_number_format CHECK (school_number IS NULL OR school_number ~ '^[A-Za-z0-9/-]{1,20}$'),
  CONSTRAINT students_username_format CHECK (username ~ '^[a-z][a-z0-9]{2,31}$'),
  CONSTRAINT students_starting_password CHECK (must_change_password = (starting_password_expires_at IS NOT NULL)),
  CONSTRAINT students_school_id_id_unique UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX students_username_unique ON students (username);
CREATE UNIQUE INDEX students_school_number_unique ON students (school_id, lower(school_number)) WHERE school_number IS NOT NULL;
CREATE INDEX students_school_name ON students (school_id, name, id);

-- Which class a pupil belongs to. One class per pupil for now (the key is the pupil); a class with pupils cannot be removed.
CREATE TABLE class_enrolments (
  school_id uuid NOT NULL,
  student_id uuid PRIMARY KEY,
  class_id uuid NOT NULL,
  enrolled_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, class_id) REFERENCES classes (school_id, id)
);
CREATE INDEX class_enrolments_class ON class_enrolments (school_id, class_id);

-- Pupil sessions, kept apart from staff sessions; the cookie holds a random token and only its SHA-256 is stored.
CREATE TABLE student_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  token_hash bytea NOT NULL UNIQUE,
  school_id uuid NOT NULL,
  student_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE
);
CREATE INDEX student_sessions_student ON student_sessions (student_id);
CREATE INDEX student_sessions_expires ON student_sessions (expires_at);

-- Sprint 12 (folded in before release): homework set by a teacher for a class and subject on their own timetable.
-- marking_minutes and mark_by are the setter's marking estimate and the day they plan to finish it; until marked_at is set
-- the estimate counts as committed work in the capacity rules, like an open task. load_flagged records that the class
-- already had two or more pieces of homework due that day when this one was set (plan Phase 4: warn, never block).
CREATE TABLE homework (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools (id),
  class_id uuid NOT NULL,
  subject_id uuid NOT NULL,
  set_by uuid NOT NULL,
  title text NOT NULL,
  details text,
  due_on date NOT NULL,
  marking_minutes integer,
  mark_by date,
  marked_at timestamptz,
  load_flagged boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT homework_title_length CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
  CONSTRAINT homework_details_length CHECK (details IS NULL OR char_length(btrim(details)) BETWEEN 1 AND 1000),
  CONSTRAINT homework_marking_range CHECK (marking_minutes IS NULL OR marking_minutes BETWEEN 5 AND 600),
  CONSTRAINT homework_marking_pair CHECK ((marking_minutes IS NULL) = (mark_by IS NULL)),
  CONSTRAINT homework_mark_after_due CHECK (mark_by IS NULL OR mark_by >= due_on),
  CONSTRAINT homework_marked_needs_estimate CHECK (marked_at IS NULL OR marking_minutes IS NOT NULL),
  CONSTRAINT homework_school_id_id_unique UNIQUE (school_id, id),
  FOREIGN KEY (school_id, class_id) REFERENCES classes (school_id, id),
  FOREIGN KEY (school_id, subject_id) REFERENCES subjects (school_id, id),
  FOREIGN KEY (school_id, set_by) REFERENCES users (school_id, id)
);
CREATE INDEX homework_class_due ON homework (school_id, class_id, due_on);
CREATE INDEX homework_setter ON homework (school_id, set_by, due_on);

-- A paper hand-in the teacher ticked on the class list. A row means handed in; undoing the tick deletes it. Only the time
-- and who recorded it are kept.
CREATE TABLE homework_status (
  homework_id uuid NOT NULL,
  student_id uuid NOT NULL,
  school_id uuid NOT NULL,
  handed_in_at timestamptz NOT NULL,
  recorded_by uuid NOT NULL,
  PRIMARY KEY (homework_id, student_id),
  FOREIGN KEY (school_id, homework_id) REFERENCES homework (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, recorded_by) REFERENCES users (school_id, id)
);
CREATE INDEX homework_status_student ON homework_status (school_id, student_id);

-- Sprint 13 (folded in before release): guardians. A guardian is a name and a sign-in, like a pupil: no email, phone,
-- address or MyKad number. Links are made by the administrator only. Each link stores the relationship type, never the
-- circumstances; a refused or removed link keeps a reason code from a fixed list, never free text.
CREATE TYPE guardian_relationship AS ENUM ('mother', 'father', 'guardian', 'grandparent', 'relative', 'other');
CREATE TYPE guardian_link_status AS ENUM ('active', 'refused', 'removed');
CREATE TYPE guardian_link_end_reason AS ENUM (
  'not_my_child', 'not_responsible', 'other',
  'entered_in_error', 'guardian_asked', 'school_decision', 'pupil_left'
);

CREATE TABLE guardians (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools (id),
  name text NOT NULL,
  -- "penjaga." then the first-name letters and digits, so the one sign-in box can tell a guardian from a pupil.
  username text NOT NULL,
  password_hash text NOT NULL,
  must_change_password boolean NOT NULL DEFAULT true,
  starting_password_expires_at timestamptz,
  status student_status NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT guardians_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT guardians_username_format CHECK (username ~ '^penjaga\.[a-z][a-z0-9]{2,31}$'),
  CONSTRAINT guardians_starting_password CHECK (must_change_password = (starting_password_expires_at IS NOT NULL)),
  CONSTRAINT guardians_school_id_id_unique UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX guardians_username_unique ON guardians (username);
CREATE INDEX guardians_school_name ON guardians (school_id, name, id);

CREATE TABLE guardian_links (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL,
  guardian_id uuid NOT NULL,
  student_id uuid NOT NULL,
  relationship guardian_relationship NOT NULL,
  status guardian_link_status NOT NULL DEFAULT 'active',
  end_reason guardian_link_end_reason,
  created_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  FOREIGN KEY (school_id, guardian_id) REFERENCES guardians (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, created_by) REFERENCES users (school_id, id),
  CONSTRAINT guardian_links_end CHECK ((status = 'active') = (end_reason IS NULL AND ended_at IS NULL)),
  -- Refusal reasons belong to the guardian, removal reasons to the administrator.
  CONSTRAINT guardian_links_reason_kind CHECK (
    status <> 'refused' OR end_reason IN ('not_my_child', 'not_responsible', 'other')
  ),
  CONSTRAINT guardian_links_removal_kind CHECK (
    status <> 'removed' OR end_reason IN ('entered_in_error', 'guardian_asked', 'school_decision', 'pupil_left')
  ),
  CONSTRAINT guardian_links_school_id_id_unique UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX guardian_links_active_unique ON guardian_links (guardian_id, student_id) WHERE status = 'active';
CREATE INDEX guardian_links_guardian ON guardian_links (school_id, guardian_id);
CREATE INDEX guardian_links_student ON guardian_links (school_id, student_id);

-- Guardian sessions: their own table and cookie, as for pupils.
CREATE TABLE guardian_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  token_hash bytea NOT NULL UNIQUE,
  school_id uuid NOT NULL,
  guardian_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  FOREIGN KEY (school_id, guardian_id) REFERENCES guardians (school_id, id) ON DELETE CASCADE
);
CREATE INDEX guardian_sessions_guardian ON guardian_sessions (guardian_id);
CREATE INDEX guardian_sessions_expires ON guardian_sessions (expires_at);

-- Sprint 13 part 2: a guardian asks one of the child's teachers for a meeting. The request reaches the teacher only in working
-- hours (deliver_at, worked out as for tasks); the teacher sees the guardian's name only. Topic, time of day and the
-- teacher's decline reason come from fixed lists: no free text, so nothing about a family is written down.
CREATE TYPE meeting_topic AS ENUM ('homework', 'progress', 'conduct', 'other');
CREATE TYPE meeting_time_of_day AS ENUM ('morning', 'afternoon', 'any');
CREATE TYPE meeting_status AS ENUM ('pending', 'accepted', 'declined', 'withdrawn', 'cancelled');
CREATE TYPE meeting_decline_reason AS ENUM ('see_other_teacher', 'not_available', 'other');

CREATE TABLE meeting_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL,
  -- Through the guardian's link, so a request ends with the link (status 'cancelled') and goes when the link is deleted.
  link_id uuid NOT NULL,
  teacher_id uuid NOT NULL,
  topic meeting_topic NOT NULL,
  time_of_day meeting_time_of_day NOT NULL,
  status meeting_status NOT NULL DEFAULT 'pending',
  deliver_at timestamptz NOT NULL,
  meeting_at timestamptz,
  decline_reason meeting_decline_reason,
  created_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz,
  FOREIGN KEY (school_id, link_id) REFERENCES guardian_links (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, teacher_id) REFERENCES users (school_id, id),
  CONSTRAINT meeting_requests_accepted CHECK ((status = 'accepted') = (meeting_at IS NOT NULL)),
  CONSTRAINT meeting_requests_declined CHECK ((status = 'declined') = (decline_reason IS NOT NULL)),
  CONSTRAINT meeting_requests_closed CHECK ((status = 'pending') = (closed_at IS NULL))
);
CREATE UNIQUE INDEX meeting_requests_pending_unique ON meeting_requests (link_id, teacher_id) WHERE status = 'pending';
CREATE INDEX meeting_requests_teacher ON meeting_requests (school_id, teacher_id, deliver_at);
CREATE INDEX meeting_requests_link ON meeting_requests (school_id, link_id);

-- Sprint 14: a removed staff login. The school is the institution and its staff logins sit beneath it. Removing one ends
-- access at once and for good: the row stays, so tasks, homework and records keep the name, but the email, password and
-- sign-in time are cleared (see features/users/server/users.service.ts).
ALTER TABLE users ADD COLUMN removed_at timestamptz;
ALTER TABLE users ADD CONSTRAINT users_removed_disabled CHECK (removed_at IS NULL OR (status = 'disabled' AND password_hash IS NULL));

-- Sprint 14: the teacher who set a piece of homework writes to one pupil about it (plan: teacher to pupil communication only
-- on homework, logged). The pupil cannot reply. A comment is never edited or deleted on its own; the teacher may hide it,
-- and it goes only with the homework. The audit log keeps ids, never the text.
CREATE TABLE homework_comments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL,
  homework_id uuid NOT NULL,
  student_id uuid NOT NULL,
  author_id uuid NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  hidden_at timestamptz,
  FOREIGN KEY (school_id, homework_id) REFERENCES homework (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, author_id) REFERENCES users (school_id, id),
  CONSTRAINT homework_comments_body_length CHECK (char_length(btrim(body)) BETWEEN 1 AND 300)
);
CREATE INDEX homework_comments_pupil ON homework_comments (school_id, student_id, homework_id, created_at);
CREATE INDEX homework_comments_homework ON homework_comments (school_id, homework_id, created_at);

