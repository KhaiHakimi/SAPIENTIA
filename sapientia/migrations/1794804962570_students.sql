-- Phase 4, Sprint 11: pupil accounts, their class, and their sessions. See docs/phase-4-students.md.
-- Data minimisation: a pupil is a name, a class and an optional school-issued number. No MyKad number, birth date,
-- address, contact details, photo or sign-in times are stored.

CREATE TYPE student_status AS ENUM ('active', 'disabled');

-- Pupils are not rows in users: no staff query can return a pupil, and no pupil session can pass a staff check.
CREATE TABLE students (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  school_id uuid NOT NULL REFERENCES schools (id),
  name text NOT NULL,
  school_number text,
  -- Generated by the app (first-name letters plus digits), stored in lower case, unique across schools: sign-in has only it.
  username text NOT NULL,
  -- argon2id in PHC form: of the starting password from the slip until the pupil chooses their own.
  password_hash text NOT NULL,
  must_change_password boolean NOT NULL DEFAULT true,
  -- The slip's password stops working at this time; null once the pupil has chosen their own.
  starting_password_expires_at timestamptz,
  status student_status NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT students_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT students_school_number_format CHECK (school_number IS NULL OR school_number ~ '^[A-Za-z0-9/-]{1,20}$'),
  CONSTRAINT students_username_format CHECK (username ~ '^[a-z][a-z0-9]{2,31}$'),
  CONSTRAINT students_starting_password CHECK (must_change_password = (starting_password_expires_at IS NOT NULL)),
  CONSTRAINT students_school_id_id_unique UNIQUE (school_id, id)
);
CREATE UNIQUE INDEX students_username_unique ON students (username);
CREATE UNIQUE INDEX students_school_number_unique ON students (school_id, lower(school_number)) WHERE school_number IS NOT NULL;
CREATE INDEX students_school_name ON students (school_id, name, id);

-- Which class a pupil belongs to. One class per pupil for now (the key is the pupil); a class with pupils cannot be removed.
CREATE TABLE class_enrolments (
  school_id uuid NOT NULL,
  student_id uuid PRIMARY KEY,
  class_id uuid NOT NULL,
  enrolled_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE,
  FOREIGN KEY (school_id, class_id) REFERENCES classes (school_id, id)
);
CREATE INDEX class_enrolments_class ON class_enrolments (school_id, class_id);

-- Pupil sessions, kept apart from staff sessions; the cookie holds a random token and only its SHA-256 is stored.
CREATE TABLE student_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  token_hash bytea NOT NULL UNIQUE,
  school_id uuid NOT NULL,
  student_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  FOREIGN KEY (school_id, student_id) REFERENCES students (school_id, id) ON DELETE CASCADE
);
CREATE INDEX student_sessions_student ON student_sessions (student_id);
CREATE INDEX student_sessions_expires ON student_sessions (expires_at);

-- Down Migration
DROP TABLE student_sessions;
DROP TABLE class_enrolments;
DROP TABLE students;
DROP TYPE student_status;
